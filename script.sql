-- Usuário da plataforma. senha guarda o hash BCrypt (60 caracteres).
CREATE TABLE T_SU_USUARIO (
    id          NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR2(100) NOT NULL,
    username    VARCHAR2(30),
    senha       VARCHAR2(60)  NOT NULL,
    cpf         CHAR(11)      NOT NULL,
    viewMinutes NUMBER(10)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SU_USUARIO PRIMARY KEY (id),
    CONSTRAINT UK_SU_USUARIO_CPF UNIQUE (cpf),
    CONSTRAINT CK_SU_USUARIO_MINUTOS CHECK (viewMinutes >= 0)
);

-- Saldo de pontos do usuário (1 registro por usuário).
CREATE TABLE T_SU_PONTOS (
    id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    usuarioId       NUMBER(10) NOT NULL,
    earnedPoints    NUMBER(10) DEFAULT 0 NOT NULL,
    dataAtualizacao TIMESTAMP  NOT NULL,
    CONSTRAINT PK_SU_PONTOS PRIMARY KEY (id),
    CONSTRAINT UK_SU_PONTOS_USUARIO UNIQUE (usuarioId),
    CONSTRAINT FK_SU_PONTOS_USUARIO FOREIGN KEY (usuarioId)
        REFERENCES T_SU_USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT CK_SU_PONTOS_VALOR CHECK (earnedPoints >= 0)
);

-- Passagens (tickets de transporte) emitidas para o usuário.
CREATE TABLE T_SU_PASSAGEM (
    id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    usuarioId   NUMBER(10) NOT NULL,
    tickets     NUMBER(10) NOT NULL,
    dataEmissao TIMESTAMP  NOT NULL,
    CONSTRAINT PK_SU_PASSAGEM PRIMARY KEY (id),
    CONSTRAINT FK_SU_PASSAGEM_USUARIO FOREIGN KEY (usuarioId)
        REFERENCES T_SU_USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT CK_SU_PASSAGEM_QTD CHECK (tickets > 0)
);

-- Cálculos de CO2 economizado (em gramas) ao trocar o carro pelo ônibus.
CREATE TABLE T_SU_CO2 (
    id               NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    usuarioId        NUMBER(10)     NOT NULL,
    distanciaKm      NUMBER(10, 2)  NOT NULL,
    co2Economizado   NUMBER(12, 2)  NOT NULL,
    passageiroOnibus NUMBER(5)      NOT NULL,
    dataCalculo      TIMESTAMP      NOT NULL,
    CONSTRAINT PK_SU_CO2 PRIMARY KEY (id),
    CONSTRAINT FK_SU_CO2_USUARIO FOREIGN KEY (usuarioId)
        REFERENCES T_SU_USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT CK_SU_CO2_DISTANCIA CHECK (distanciaKm > 0),
    CONSTRAINT CK_SU_CO2_PASSAGEIROS CHECK (passageiroOnibus > 0)
);

